# ### Observations / data quality notes
# 
# **Missing values**
# - Very sparse: `electrodes_problems` (99.86%), `infarction_stadium2` (99.5%), `pacemaker` (98.7%), `burst_noise` (97.2%), `baseline_drift` (92.7%), `extra_beats` (91.1%), `static_noise` (85.0%), `infarction_stadium1` (74.3%).
#   - In the signal-quality columns, **NaN most likely means "no problem noted"**, not "unknown". → Turn them into binary flags (`has_static_noise`, `has_pacemaker`, …) instead of dropping them. The flags can be used to filter or weight noisy signals.
#   - The values are free text and messy: `pacemaker` has `"ja, pacemaker"`, `"PACE????, nan"`, `"?, nan"`; `electrodes_problems` has `"V1???"`. The text is German ("ja" = yes), as are many `report` strings (e.g. *"sinusrhythmus normales ekg"*).
#   - `infarction_stadium1` contains a literal `"unknown"` category (3,430 rows), which is a second kind of missing value besides NaN.
# - `height` (68%) and `weight` (57%) are mostly missing. Every record with a height is `validated_by_human == True`, so the missingness is **not random** and depends on how the record was processed.
# - `heart_axis` is 39% missing, `validated_by` 43%, `nurse` 6.8%, `site` 0.08%.
# 
# **Correlations (heatmap)**
# - **`patient_id` vs `nurse` = −0.69**: both are anonymised IDs, so the value means nothing numerically. It is an artefact of collection time. Nurses 2–11 appear only from 1986–1997. Records from 1998–2001 have only nurse 0/1. Nurse 0 is the one linked to auto-generated reports (5,841 of 6,813). Patient IDs are partly ordered by time. → Treat `patient_id`, `nurse`, `site`, `validated_by` and `device` as **categorical**. Leave them out of Pearson correlation and never use them as model features. `patient_id` is only for grouping.
# - `initial_autogenerated_report` vs `validated_by_human` = −0.89: expected, since an auto-generated report usually was not validated by a human. They are almost redundant.
# - `sex` vs `height` (−0.57) / `weight` (−0.44), and `height` vs `weight` (0.55): plausible physiology (sex = 1 is female).
# - **Blank cells** (`height`/`validated_by` × `validated_by_human`) are not bugs. Wherever height or validated_by is present, `validated_by_human` is always True, so it is constant there and the correlation is undefined.
# - `strat_fold` vs `validated_by_human` = 0.21: folds 9–10 hold the human-validated records by design, so they are the recommended test/validation sets (`test_fold = 10` ✔).
# 
# **Duplicates / patients**
# - No fully duplicated rows (`scp_codes` turned into JSON to be hashable).
# - 21,799 records from 18,869 patients: 2,111 patients have ≥2 ECGs (up to 5+). → Always split by patient. `strat_fold` already does this, so don't reshuffle with a random split.
# 
# **Labels**
# - 1.9% of records have an **empty** `diagnostic_superclass` (`[]`): they have no diagnostic SCP code, only form or rhythm codes. → Drop them or handle them explicitly.
# - Strongly imbalanced: NORM alone ≈ 42%, and many labels co-occur (multi-label).
# - `aggregate_diagnostic` returns `list(set(...))`, so the order is arbitrary and `value_counts` lists the same combination twice (e.g. `[STTC, CD]` 1.24% and `[CD, STTC]` 0.92%). → Use `sorted(set(tmp))`, and use `MultiLabelBinarizer` for targets.
# - `aggregate_diagnostic` ignores the likelihood values in `scp_codes`. Statements with likelihood < 100 (or 0 = unknown) count the same as certain ones, so think about a threshold.
# 
# **Other**
# - Recordings span 1984-11 to 2001-06 on 11 device types (`CS100 3`, `CS-12`, `AT-6 …`). Device and era can confound labels, so check label distribution per device.
# - `second_opinion` is True for only 555 records.

